package twofactor

import (
	"time"
)

// Config holds the configuration options for the twofactor plugin module.
type Config struct {
	// Protector encrypts and decrypts factor secrets at rest.
	// If nil, defaults to an AES-256-GCM protector initialized with a secure random key.
	Protector SecretProtector

	// Issuer is the default organization or application name included in otpauth:// URIs.
	Issuer string

	// StepDuration is the time interval for TOTP tokens (RFC 6238 recommends 30 seconds).
	StepDuration time.Duration

	// SkewSteps is the number of time-steps allowed before and after current time to tolerate clock drift.
	// Default is 1 (covering +/- 30 seconds).
	SkewSteps int

	// ChallengeTTL is the lifetime for ephemeral MFA challenges.
	ChallengeTTL time.Duration

	// DefaultRecoveryCodesCount is the number of recovery codes generated by default.
	DefaultRecoveryCodesCount int

	// EnforceMFAOnSignIn controls whether the plugin verifies that users with active 2FA
	// are not granted final sessions without completing MFA verification.
	EnforceMFAOnSignIn bool
}

// Option configures the Config struct.
type Option func(*Config)

// WithSecretProtector sets a custom SecretProtector implementation.
func WithSecretProtector(p SecretProtector) Option {
	return func(c *Config) {
		if p != nil {
			c.Protector = p
		}
	}
}

// WithEncryptionKey sets the 32-byte master key for the default AES-GCM protector.
func WithEncryptionKey(key []byte) Option {
	return func(c *Config) {
		protector, err := NewAESGCMProtector(key)
		if err == nil {
			c.Protector = protector
		}
	}
}

// WithIssuer sets the default issuer name for TOTP provisioning URIs.
func WithIssuer(issuer string) Option {
	return func(c *Config) {
		if issuer != "" {
			c.Issuer = issuer
		}
	}
}

// WithSkewSteps sets the allowed clock skew steps (e.g. 1 allows +/- 1 step).
func WithSkewSteps(steps int) Option {
	return func(c *Config) {
		if steps >= 0 {
			c.SkewSteps = steps
		}
	}
}

// WithChallengeTTL sets the duration for ephemeral MFA challenges.
func WithChallengeTTL(ttl time.Duration) Option {
	return func(c *Config) {
		if ttl > 0 {
			c.ChallengeTTL = ttl
		}
	}
}

// WithDefaultRecoveryCodesCount sets the default number of recovery codes generated.
func WithDefaultRecoveryCodesCount(count int) Option {
	return func(c *Config) {
		if count > 0 {
			c.DefaultRecoveryCodesCount = count
		}
	}
}

// WithEnforceMFAOnSignIn configures whether to require MFA challenges upon primary sign in.
func WithEnforceMFAOnSignIn(enforce bool) Option {
	return func(c *Config) {
		c.EnforceMFAOnSignIn = enforce
	}
}

func defaultConfig() Config {
	randomKey, _ := GenerateRandomKey()
	protector, _ := NewAESGCMProtector(randomKey)

	return Config{
		Protector:                 protector,
		Issuer:                    "GoModularAuth",
		StepDuration:              30 * time.Second,
		SkewSteps:                 1,
		ChallengeTTL:              5 * time.Minute,
		DefaultRecoveryCodesCount: 10,
		EnforceMFAOnSignIn:        false,
	}
}
