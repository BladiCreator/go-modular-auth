// mockProvider implements provider.Provider for testing without live HTTP network.
type mockProvider struct {
	name                string
	allowedRedirectURIs []string
	tokenResp           *provider.TokenResponse
	profile             *provider.ProviderProfile
	exchangeErr         error
	profileErr          error
}

var _ provider.Provider = (*mockProvider)(nil)

func (m *mockProvider) Name() string { return m.name }

func (m *mockProvider) AuthCodeURL(state string, opts ...provider.AuthCodeOption) string {
	var c provider.AuthCodeConfig
	for _, opt := range opts {
		opt(&c)
	}
	return "https://mock.provider.com/auth?state=" + state + "&redirect_uri=" + c.RedirectURI
}

func (m *mockProvider) Exchange(ctx context.Context, code string, opts ...provider.ExchangeOption) (*provider.TokenResponse, error) {
	if m.exchangeErr != nil {
		return nil, m.exchangeErr
	}
	return m.tokenResp, nil
}

func (m *mockProvider) FetchProfile(ctx context.Context, tokens *provider.TokenResponse) (*provider.ProviderProfile, error) {
	if m.profileErr != nil {
		return nil, m.profileErr
	}
	return m.profile, nil
}

func (m *mockProvider) ValidateRedirectURI(redirectURI string) bool {
	for _, allowed := range m.allowedRedirectURIs {
		if allowed == redirectURI {
			return true
		}
	}
	return false
}

func setupTestAuth(t *testing.T, opts ...oauth.Option) (*auth.Auth, plugins.OAuth, *mockProvider) {
	t.Helper()

	mockP := &mockProvider{
		name:                "google",
		allowedRedirectURIs: []string{"https://app.com/callback"},
		tokenResp: &provider.TokenResponse{
			AccessToken: "mock_token_123",
			TokenType:   "Bearer",
			ExpiresIn:   3600,
		},
		profile: &provider.ProviderProfile{
			Provider:      "google",
			ProviderID:    "google_sub_999",
			Email:         "bob@example.com",
			EmailVerified: true,
			Name:          "Bob Smith",
		},
	}

	defaultOpts := []oauth.Option{
		oauth.WithProvider(mockP),
	}
	defaultOpts = append(defaultOpts, opts...)

	module := oauth.New(defaultOpts...)

	a, err := auth.New(auth.Config{
		Adapter: adaptermem.New(),
		Plugins: []auth.PluginModule{module},
	})
	if err != nil {
		t.Fatalf("failed to create core auth: %v", err)
	}

	oauthPlugin, err := auth.Get[plugins.OAuth](a)
	if err != nil {
		t.Fatalf("failed to retrieve plugins.OAuth capability: %v", err)
	}

	return a, oauthPlugin, mockP
}

func TestOAuth_AuthorizationCodeFlowAndSessionCreation(t *testing.T) {
	ctx := context.Background()
	a, oauthPlugin, mockP := setupTestAuth(t)

	// 1. BeginAuth - Initiate flow
	beginRes, err := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
		Provider:    "google",
		RedirectURI: "https://app.com/callback",
		Metadata:    map[string]string{"return_to": "/dashboard"},
	})
	if err != nil {
		t.Fatalf("unexpected BeginAuth error: %v", err)
	}

	if beginRes.State == "" {
		t.Fatal("expected non-empty state")
	}
	if beginRes.CodeVerifier == "" {
		t.Fatal("expected PKCE code verifier generated by default")
	}
	if beginRes.AuthURL == "" {
		t.Fatal("expected non-empty AuthURL")
	}

	// Disallowed redirect URI must be rejected immediately
	_, err = oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
		Provider:    "google",
		RedirectURI: "https://evil.com/callback",
	})
	if !errors.Is(err, oauth.ErrInvalidRedirectURI) {
		t.Fatalf("expected ErrInvalidRedirectURI, got %v", err)
	}

	// Unknown provider must be rejected
	_, err = oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
		Provider:    "nonexistent",
		RedirectURI: "https://app.com/callback",
	})
	if !errors.Is(err, oauth.ErrProviderNotFound) {
		t.Fatalf("expected ErrProviderNotFound, got %v", err)
	}

	// 2. CompleteAuth - First time authentication (New User Sign-up)
	authRes, err := oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
		Provider:    "google",
		Code:        "auth_code_xyz",
		State:       beginRes.State,
		RedirectURI: "https://app.com/callback",
		Session: auth.SessionOptions{
			IPAddress: "192.168.1.1",
			UserAgent: "Mozilla/5.0",
		},
	})
	if err != nil {
		t.Fatalf("unexpected CompleteAuth error: %v", err)
	}

	if !authRes.IsNewUser {
		t.Fatal("expected new user created")
	}
	if authRes.User == nil || authRes.User.Email != "bob@example.com" {
		t.Fatalf("unexpected user: %+v", authRes.User)
	}
	if authRes.Account == nil || authRes.Account.ProviderID != "google_sub_999" {
		t.Fatalf("unexpected account: %+v", authRes.Account)
	}
	if authRes.Session == nil || authRes.Token == "" {
		t.Fatal("expected active session and plaintext session token")
	}

	// 3. Verify that the issued Session token is recognized by Core Auth
	sessionRes, err := a.RequireSession(ctx, authRes.Token)
	if err != nil {
		t.Fatalf("core RequireSession failed for token: %v", err)
	}
	if sessionRes.User.ID != authRes.User.ID {
		t.Fatalf("session user ID mismatch: got %s, want %s", sessionRes.User.ID, authRes.User.ID)
	}

	// 4. Anti-Replay: Attempting to reuse the same state must be rejected
	_, err = oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
		Provider:    "google",
		Code:        "auth_code_xyz",
		State:       beginRes.State,
		RedirectURI: "https://app.com/callback",
	})
	if !errors.Is(err, oauth.ErrStateAlreadyConsumed) {
		t.Fatalf("expected ErrStateAlreadyConsumed on replay, got %v", err)
	}

	// 5. Subsequent Login with existing account
	beginRes2, err := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
		Provider:    "google",
		RedirectURI: "https://app.com/callback",
	})
	if err != nil {
		t.Fatalf("second BeginAuth error: %v", err)
	}

	authRes2, err := oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
		Provider:    "google",
		Code:        "auth_code_2",
		State:       beginRes2.State,
		RedirectURI: "https://app.com/callback",
	})
	if err != nil {
		t.Fatalf("second CompleteAuth error: %v", err)
	}

	if authRes2.IsNewUser {
		t.Fatal("expected existing user, but flagged as new user")
	}
	if authRes2.User.ID != authRes.User.ID {
		t.Fatalf("expected same user ID %s, got %s", authRes.User.ID, authRes2.User.ID)
	}

	// Mismatched redirect URI at CompleteAuth
	beginRes3, _ := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
		Provider:    "google",
		RedirectURI: "https://app.com/callback",
	})
	_, err = oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
		Provider:    "google",
		Code:        "code",
		State:       beginRes3.State,
		RedirectURI: "https://different.com/callback",
	})
	if !errors.Is(err, oauth.ErrInvalidRedirectURI) {
		t.Fatalf("expected ErrInvalidRedirectURI, got %v", err)
	}

	_ = mockP
}

func TestOAuth_PreventUnsafeAutomaticAccountLinking(t *testing.T) {
	ctx := context.Background()

	// Scenario: An existing user already exists with email "alice@target.com"
	t.Run("Default LinkingPolicyExplicitOnly blocks unsafe automatic linking", func(t *testing.T) {
		a, oauthPlugin, mockP := setupTestAuth(t, oauth.WithLinkingPolicy(oauth.LinkingPolicyExplicitOnly))

		// Create user alice via password / core sign up
		aliceSignUp, err := a.SignUp(ctx, auth.SignUpInput{
			Email:    "alice@target.com",
			Password: "securepassword123",
		})
		if err != nil {
			t.Fatalf("failed to create existing user: %v", err)
		}

		// Attacker attempts OAuth login with a provider presenting email alice@target.com
		mockP.profile = &provider.ProviderProfile{
			Provider:      "google",
			ProviderID:    "attacker_sub_456",
			Email:         "alice@target.com",
			EmailVerified: true,
		}

		beginRes, err := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
			Provider:    "google",
			RedirectURI: "https://app.com/callback",
		})
		if err != nil {
			t.Fatal(err)
		}

		// Must FAIL with ErrAccountLinkingRequiresConsent!
		_, err = oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
			Provider:    "google",
			Code:        "code",
			State:       beginRes.State,
			RedirectURI: "https://app.com/callback",
		})
		if !errors.Is(err, oauth.ErrAccountLinkingRequiresConsent) {
			t.Fatalf("SECURITY VIOLATION: expected ErrAccountLinkingRequiresConsent, got %v", err)
		}

		// Verify alice's account was NOT linked to attacker_sub_456
		accounts, err := oauthPlugin.ListAccounts(ctx, aliceSignUp.User.ID)
		if err != nil {
			t.Fatal(err)
		}
		for _, acc := range accounts {
			if acc.ProviderID == "attacker_sub_456" {
				t.Fatal("SECURITY VIOLATION: provider account was linked without consent!")
			}
		}
	})

	t.Run("LinkingPolicyDisabled rejects collisions with ErrAccountConflict", func(t *testing.T) {
		a, oauthPlugin, mockP := setupTestAuth(t, oauth.WithLinkingPolicy(oauth.LinkingPolicyDisabled))

		_, err := a.SignUp(ctx, auth.SignUpInput{
			Email:    "bob@target.com",
			Password: "securepassword123",
		})
		if err != nil {
			t.Fatal(err)
		}

		mockP.profile = &provider.ProviderProfile{
			Provider:      "google",
			ProviderID:    "sub_123",
			Email:         "bob@target.com",
			EmailVerified: true,
		}

		beginRes, _ := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
			Provider:    "google",
			RedirectURI: "https://app.com/callback",
		})

		_, err = oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
			Provider:    "google",
			Code:        "code",
			State:       beginRes.State,
			RedirectURI: "https://app.com/callback",
		})
		if !errors.Is(err, oauth.ErrAccountConflict) {
			t.Fatalf("expected ErrAccountConflict, got %v", err)
		}
	})

	t.Run("LinkingPolicyVerifiedEmail requires verification on both ends", func(t *testing.T) {
		a, oauthPlugin, mockP := setupTestAuth(t, oauth.WithLinkingPolicy(oauth.LinkingPolicyVerifiedEmail))

		// 1. Existing user with UNVERIFIED email
		unverifiedUserSignUp, err := a.SignUp(ctx, auth.SignUpInput{
			Email:    "charlie@target.com",
			Password: "securepassword123",
		})
		if err != nil {
			t.Fatal(err)
		}

		mockP.profile = &provider.ProviderProfile{
			Provider:      "google",
			ProviderID:    "google_sub_charlie",
			Email:         "charlie@target.com",
			EmailVerified: true,
		}

		beginRes1, _ := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
			Provider:    "google",
			RedirectURI: "https://app.com/callback",
		})

		// Should reject because core user email is unverified
		_, err = oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
			Provider:    "google",
			Code:        "code",
			State:       beginRes1.State,
			RedirectURI: "https://app.com/callback",
		})
		if !errors.Is(err, oauth.ErrUnverifiedEmailLinkingProhibited) {
			t.Fatalf("expected ErrUnverifiedEmailLinkingProhibited, got %v", err)
		}

		// 2. Mark user email verified in core store
		u, _ := a.Store().Users().GetByID(ctx, unverifiedUserSignUp.User.ID)
		u.EmailVerified = true
		_ = a.Store().Users().Update(ctx, u)

		// Provider email unverified
		mockP.profile.EmailVerified = false
		beginRes2, _ := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
			Provider:    "google",
			RedirectURI: "https://app.com/callback",
		})
		_, err = oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
			Provider:    "google",
			Code:        "code",
			State:       beginRes2.State,
			RedirectURI: "https://app.com/callback",
		})
		if !errors.Is(err, oauth.ErrUnverifiedEmailLinkingProhibited) {
			t.Fatalf("expected ErrUnverifiedEmailLinkingProhibited, got %v", err)
		}

		// Both verified: Linking succeeds safely
		mockP.profile.EmailVerified = true
		beginRes3, _ := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
			Provider:    "google",
			RedirectURI: "https://app.com/callback",
		})
		linkRes, err := oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
			Provider:    "google",
			Code:        "code",
			State:       beginRes3.State,
			RedirectURI: "https://app.com/callback",
		})
		if err != nil {
			t.Fatalf("unexpected error when both verified: %v", err)
		}
		if linkRes.User.ID != unverifiedUserSignUp.User.ID {
			t.Fatalf("expected linked user ID %s, got %s", unverifiedUserSignUp.User.ID, linkRes.User.ID)
		}
	})
}

func TestOAuth_ExplicitAccountLinkingAndUnlinking(t *testing.T) {
	ctx := context.Background()
	a, oauthPlugin, mockP := setupTestAuth(t)

	// Create user with password
	signUpRes, err := a.SignUp(ctx, auth.SignUpInput{
		Email:    "dave@example.com",
		Password: "password_123",
	})
	if err != nil {
		t.Fatal(err)
	}

	mockP.profile = &provider.ProviderProfile{
		Provider:      "google",
		ProviderID:    "google_dave_sub",
		Email:         "dave.oauth@gmail.com",
		EmailVerified: true,
	}

	// 1. BeginLink - Initiated explicitly by authenticated user
	beginLinkRes, err := oauthPlugin.BeginLink(ctx, oauth.BeginLinkInput{
		UserID:      signUpRes.User.ID,
		Provider:    "google",
		RedirectURI: "https://app.com/callback",
	})
	if err != nil {
		t.Fatalf("BeginLink error: %v", err)
	}

	// 2. CompleteLink - Complete linking
	linkRes, err := oauthPlugin.CompleteLink(ctx, oauth.CompleteLinkInput{
		Code:        "link_auth_code",
		State:       beginLinkRes.State,
		RedirectURI: "https://app.com/callback",
	})
	if err != nil {
		t.Fatalf("CompleteLink error: %v", err)
	}

	if linkRes.Account == nil || linkRes.Account.ProviderID != "google_dave_sub" {
		t.Fatalf("unexpected linked account: %+v", linkRes.Account)
	}
	if linkRes.User.ID != signUpRes.User.ID {
		t.Fatalf("user ID mismatch: got %s, want %s", linkRes.User.ID, signUpRes.User.ID)
	}

	// 3. Prevent duplicate linking of the same provider ID to another user
	signUpRes2, err := a.SignUp(ctx, auth.SignUpInput{
		Email:    "eve@example.com",
		Password: "password_456",
	})
	if err != nil {
		t.Fatal(err)
	}

	beginLink2, _ := oauthPlugin.BeginLink(ctx, oauth.BeginLinkInput{
		UserID:      signUpRes2.User.ID,
		Provider:    "google",
		RedirectURI: "https://app.com/callback",
	})

	_, err = oauthPlugin.CompleteLink(ctx, oauth.CompleteLinkInput{
		Code:        "link_code",
		State:       beginLink2.State,
		RedirectURI: "https://app.com/callback",
	})
	if !errors.Is(err, oauth.ErrAccountAlreadyLinked) {
		t.Fatalf("expected ErrAccountAlreadyLinked, got %v", err)
	}

	// 4. List accounts: Dave has 2 accounts (password and google)
	daveAccounts, err := oauthPlugin.ListAccounts(ctx, signUpRes.User.ID)
	if err != nil || len(daveAccounts) != 2 {
		t.Fatalf("expected 2 accounts (password and google), got %v (err: %v)", daveAccounts, err)
	}

	// 5. Unlink account: Dave has password, so unlinking OAuth is permitted
	if err := oauthPlugin.UnlinkAccount(ctx, signUpRes.User.ID, "google"); err != nil {
		t.Fatalf("unexpected unlink error: %v", err)
	}

	daveAccountsAfter, _ := oauthPlugin.ListAccounts(ctx, signUpRes.User.ID)
	if len(daveAccountsAfter) != 1 {
		t.Fatalf("expected 1 remaining account (password) after unlink, got %d", len(daveAccountsAfter))
	}

	// 6. Safeguard: OAuth-only user cannot unlink sole auth method
	beginAuthRes, _ := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
		Provider:    "google",
		RedirectURI: "https://app.com/callback",
	})
	mockP.profile.ProviderID = "google_frank_sub"
	mockP.profile.Email = "frank@example.com"
	frankAuthRes, err := oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
		Provider:    "google",
		Code:        "code",
		State:       beginAuthRes.State,
		RedirectURI: "https://app.com/callback",
	})
	if err != nil {
		t.Fatal(err)
	}

	// Frank has no password, only OAuth. Unlinking must fail with ErrCannotUnlinkSoleAuthMethod
	err = oauthPlugin.UnlinkAccount(ctx, frankAuthRes.User.ID, "google")
	if !errors.Is(err, oauth.ErrCannotUnlinkSoleAuthMethod) {
		t.Fatalf("expected ErrCannotUnlinkSoleAuthMethod, got %v", err)
	}
}

func TestOAuth_EventsAndHooks(t *testing.T) {
	ctx := context.Background()
	eventsFired := make(map[auth.EventName]int)
	hooksFired := make(map[string]int)

	customHooks := oauth.NewHooks()
	customHooks.BeforeOAuthRedirect(func(ctx context.Context, in *oauth.BeginAuthInput) error {
		hooksFired["BeforeOAuthRedirect"]++
		return nil
	})
	customHooks.BeforeTokenExchange(func(ctx context.Context, providerName, code string) error {
		hooksFired["BeforeTokenExchange"]++
		return nil
	})
	customHooks.AfterProfileFetched(func(ctx context.Context, profile *provider.ProviderProfile) error {
		hooksFired["AfterProfileFetched"]++
		return nil
	})
	customHooks.AfterOAuthSignIn(func(ctx context.Context, res *oauth.AuthResult) error {
		hooksFired["AfterOAuthSignIn"]++
		return nil
	})

	a, oauthPlugin, mockP := setupTestAuth(t,
		oauth.WithHooks(customHooks),
	)

	a.Events().SubscribeAll(func(ctx context.Context, e auth.Event) {
		eventsFired[e.Name]++
	})

	mockP.profile = &provider.ProviderProfile{
		Provider:      "google",
		ProviderID:    "sub_event_test",
		Email:         "event@example.com",
		EmailVerified: true,
	}

	beginRes, err := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
		Provider:    "google",
		RedirectURI: "https://app.com/callback",
	})
	if err != nil {
		t.Fatal(err)
	}

	_, err = oauthPlugin.CompleteAuth(ctx, oauth.CompleteAuthInput{
		Provider:    "google",
		Code:        "code",
		State:       beginRes.State,
		RedirectURI: "https://app.com/callback",
	})
	if err != nil {
		t.Fatal(err)
	}

	// Check hooks fired
	if hooksFired["BeforeOAuthRedirect"] != 1 {
		t.Errorf("BeforeOAuthRedirect hook count: %d", hooksFired["BeforeOAuthRedirect"])
	}
	if hooksFired["BeforeTokenExchange"] != 1 {
		t.Errorf("BeforeTokenExchange hook count: %d", hooksFired["BeforeTokenExchange"])
	}
	if hooksFired["AfterProfileFetched"] != 1 {
		t.Errorf("AfterProfileFetched hook count: %d", hooksFired["AfterProfileFetched"])
	}
	if hooksFired["AfterOAuthSignIn"] != 1 {
		t.Errorf("AfterOAuthSignIn hook count: %d", hooksFired["AfterOAuthSignIn"])
	}

	// Check events fired
	if eventsFired[oauth.EventOAuthStateCreated] != 1 {
		t.Errorf("EventOAuthStateCreated count: %d", eventsFired[oauth.EventOAuthStateCreated])
	}
	if eventsFired[oauth.EventOAuthUserCreated] != 1 {
		t.Errorf("EventOAuthUserCreated count: %d", eventsFired[oauth.EventOAuthUserCreated])
	}
	if eventsFired[oauth.EventOAuthAccountLinked] != 1 {
		t.Errorf("EventOAuthAccountLinked count: %d", eventsFired[oauth.EventOAuthAccountLinked])
	}
	if eventsFired[oauth.EventOAuthAuthenticated] != 1 {
		t.Errorf("EventOAuthAuthenticated count: %d", eventsFired[oauth.EventOAuthAuthenticated])
	}
}

func TestOAuth_PurgeExpired(t *testing.T) {
	ctx := context.Background()
	_, oauthPlugin, _ := setupTestAuth(t, oauth.WithStateTTL(1*time.Millisecond))

	_, err := oauthPlugin.BeginAuth(ctx, oauth.BeginAuthInput{
		Provider:    "google",
		RedirectURI: "https://app.com/callback",
	})
	if err != nil {
		t.Fatal(err)
	}

	time.Sleep(5 * time.Millisecond)

	purged, err := oauthPlugin.PurgeExpired(ctx)
	if err != nil {
		t.Fatalf("PurgeExpired error: %v", err)
	}
	if purged != 1 {
		t.Fatalf("expected 1 purged state, got %d", purged)
	}
}
