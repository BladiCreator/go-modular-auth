package generator

import (
	"github.com/BladiCreator/go-modular-auth-openapi/spec"
)

type Generator struct {
	title       string
	version     string
	description string
}

func New(title, version, description string) *Generator {
	if title == "" {
		title = "Go Modular Auth API"
	}
	if version == "" {
		version = "1.0.0"
	}
	if description == "" {
		description = "Authentication and Identity API generated by go-modular-auth"
	}
	return &Generator{
		title:       title,
		version:     version,
		description: description,
	}
}

func (g *Generator) Generate(installedPluginIDs []string) *spec.Document {
	paths := make(map[string]spec.PathItem)

	// 1. Core Endpoints
	paths["/auth/sign-up/email"] = spec.PathItem{
		Summary: "Sign up with email and password",
		Post: &spec.Operation{
			Summary:     "Register a new user",
			OperationID: "signUpEmail",
			Tags:        []string{"Authentication"},
			RequestBody: &spec.RequestBody{
				Required: true,
				Content: map[string]spec.MediaType{
					"application/json": {
						Schema: &spec.Schema{
							Type: "object",
							Properties: map[string]*spec.Schema{
								"email":    {Type: "string", Format: "email"},
								"password": {Type: "string"},
							},
							Required: []string{"email", "password"},
						},
					},
				},
			},
			Responses: map[string]spec.Response{
				"201": {Description: "User successfully created"},
				"400": {Description: "Validation error"},
				"409": {Description: "Email already exists"},
			},
		},
	}

	paths["/auth/sign-in/email"] = spec.PathItem{
		Summary: "Sign in with email and password",
		Post: &spec.Operation{
			Summary:     "Authenticate user",
			OperationID: "signInEmail",
			Tags:        []string{"Authentication"},
			RequestBody: &spec.RequestBody{
				Required: true,
				Content: map[string]spec.MediaType{
					"application/json": {
						Schema: &spec.Schema{
							Type: "object",
							Properties: map[string]*spec.Schema{
								"email":    {Type: "string", Format: "email"},
								"password": {Type: "string"},
							},
							Required: []string{"email", "password"},
						},
					},
				},
			},
			Responses: map[string]spec.Response{
				"200": {Description: "Authenticated successfully"},
				"401": {Description: "Invalid credentials"},
			},
		},
	}

	paths["/auth/sign-out"] = spec.PathItem{
		Summary: "Sign out and revoke active session",
		Post: &spec.Operation{
			Summary:     "Revoke session",
			OperationID: "signOut",
			Tags:        []string{"Authentication"},
			Responses: map[string]spec.Response{
				"200": {Description: "Session revoked successfully"},
			},
		},
	}

	paths["/auth/session"] = spec.PathItem{
		Summary: "Get active session details",
		Get: &spec.Operation{
			Summary:     "Session inspection",
			OperationID: "getSession",
			Tags:        []string{"Authentication"},
			Responses: map[string]spec.Response{
				"200": {Description: "Active session returned"},
				"401": {Description: "Unauthorized"},
			},
		},
	}

	// 2. Add plugin-specific endpoints dynamically based on installed plugins
	pluginSet := make(map[string]bool)
	for _, id := range installedPluginIDs {
		pluginSet[id] = true
	}

	if pluginSet["passkeys"] {
		paths["/auth/passkey/register"] = spec.PathItem{
			Summary: "Start passkey registration ceremony",
			Post: &spec.Operation{
				Summary:     "Passkey registration",
				OperationID: "passkeyRegister",
				Tags:        []string{"Passkeys"},
				Responses: map[string]spec.Response{
					"200": {Description: "Challenge returned"},
				},
			},
		}
	}

	if pluginSet["one_time_token"] {
		paths["/auth/token/exchange"] = spec.PathItem{
			Summary: "Exchange a one-time token",
			Post: &spec.Operation{
				Summary:     "One-Time Token Exchange",
				OperationID: "exchangeOTT",
				Tags:        []string{"Tokens"},
				Responses: map[string]spec.Response{
					"200": {Description: "Token consumed successfully"},
					"400": {Description: "Token invalid or expired"},
				},
			},
		}
	}

	if pluginSet["scim"] {
		paths["/scim/v2/Users"] = spec.PathItem{
			Summary: "SCIM 2.0 Users Provisioning",
			Get: &spec.Operation{
				Summary:     "List Users",
				OperationID: "scimListUsers",
				Tags:        []string{"SCIM"},
				Responses: map[string]spec.Response{
					"200": {Description: "SCIM ListResponse"},
				},
			},
			Post: &spec.Operation{
				Summary:     "Create User",
				OperationID: "scimCreateUser",
				Tags:        []string{"SCIM"},
				Responses: map[string]spec.Response{
					"201": {Description: "User created"},
				},
			},
		}
	}

	if pluginSet["oidc_provider"] {
		paths["/.well-known/openid-configuration"] = spec.PathItem{
			Summary: "OpenID Connect Discovery Document",
			Get: &spec.Operation{
				Summary:     "OIDC Discovery",
				OperationID: "oidcDiscovery",
				Tags:        []string{"OIDC Provider"},
				Responses: map[string]spec.Response{
					"200": {Description: "Discovery document"},
				},
			},
		}
	}

	return &spec.Document{
		OpenAPI: "3.1.0",
		Info: spec.Info{
			Title:       g.title,
			Version:     g.version,
			Description: g.description,
		},
		Paths: paths,
		Components: &spec.Components{
			SecuritySchemes: map[string]spec.SecurityScheme{
				"bearerAuth": {
					Type:         "http",
					Scheme:       "bearer",
					BearerFormat: "Bearer <token>",
					Description:  "Session token or JWT passed in the Authorization header",
				},
			},
		},
	}
}
